fn anp(a: f64) -> f64 {
    let w = a % D2PI;
    if w < 0.0 { w + D2PI } else { w }
}

fn mean_anomaly_moon(t: f64) -> f64 {
    (485868.249036 + t * (1717915923.2178 + t * (31.8792 + t * (0.051635 + t * (-0.00024470)))))
        % TURNAS
        * ARCSEC_TO_RAD
}

fn moon_mean_argument_of_latitude(t: f64) -> f64 {
    (335779.526232 + t * (1739527262.8478 + t * (-12.7512 + t * (-0.001037 + t * (0.00000417)))))
        % TURNAS
        * ARCSEC_TO_RAD
}

fn moon_mean_longitude_ascending_node(t: f64) -> f64 {
    (450160.398036 + t * (-6962890.5431 + t * (7.4722 + t * (0.007702 + t * (-0.00005939)))))
        % TURNAS
        * ARCSEC_TO_RAD
}

fn mean_obliquity_06_rad(t: f64) -> f64 {
    let inner1 = -0.000000576 + (-0.0000000434) * t;
    let inner2 = 0.00200340 + inner1 * t;
    let inner3 = -0.0001831 + inner2 * t;
    let inner4 = -46.836769 + inner3 * t;
    (84381.406 + inner4 * t) * ARCSEC_TO_RAD
}

pub fn nutation_angles_2000a(jd_tt: f64) -> Option<(f64, f64)> {
    if !jd_tt.is_finite() {
        return None;
    }
    let t = (jd_tt - 2451545.0) / 36525.0;

    let el = mean_anomaly_moon(t);
    let elp = (1287104.79305
        + t * (129596581.0481 + t * (-0.5532 + t * (0.000136 + t * (-0.00001149)))))
        % TURNAS
        * ARCSEC_TO_RAD;
    let f = moon_mean_argument_of_latitude(t);
    let d = (1072260.70369
        + t * (1602961601.2090 + t * (-6.3706 + t * (0.006593 + t * (-0.00003169)))))
        % TURNAS
        * ARCSEC_TO_RAD;
    let om = moon_mean_longitude_ascending_node(t);

    let mut dp = 0.0_f64;
    let mut de = 0.0_f64;
    for &(nl, nlp, nf, nd, nom, sp, spt, cp, ce, cet, se) in NUT_LS.iter().rev() {
        let arg = (f64::from(nl) * el
            + f64::from(nlp) * elp
            + f64::from(nf) * f
            + f64::from(nd) * d
            + f64::from(nom) * om)
            % D2PI;
        let (sarg, carg) = (arg.sin(), arg.cos());
        dp += (sp + spt * t) * sarg + cp * carg;
        de += (ce + cet * t) * carg + se * sarg;
    }
    let dpsils = dp * U2R;
    let depsls = de * U2R;

    let al = (2.35555598 + 8328.6914269554 * t) % D2PI;
    let af = (1.627905234 + 8433.466158131 * t) % D2PI;
    let ad = (5.198466741 + 7771.3771468121 * t) % D2PI;
    let aom = (2.18243920 - 33.757045 * t) % D2PI;
    let apa = (0.024381750 + 0.00000538691 * t) * t;
    let alme = anp(4.402608842 + 2608.7903141574 * t);
    let alve = anp(3.176146697 + 1021.3285546211 * t);
    let alea = anp(1.753470314 + 628.3075849991 * t);
    let alma = anp(6.203480913 + 334.0612426700 * t);
    let alju = anp(0.599546497 + 52.9690962641 * t);
    let alsa = anp(0.874016757 + 21.3299104960 * t);
    let alur = anp(5.481293872 + 7.4781598567 * t);
    let alne = (5.321159000 + 3.8127774000 * t) % D2PI;

    dp = 0.0;
    de = 0.0;
    for &(nl, nf, nd, nom, nme, nve, nea, nma, nju, nsa, nur, nne, npa, sp, cp, se, ce) in
        NUT_PL.iter().rev()
    {
        let arg = (f64::from(nl) * al
            + f64::from(nf) * af
            + f64::from(nd) * ad
            + f64::from(nom) * aom
            + f64::from(nme) * alme
            + f64::from(nve) * alve
            + f64::from(nea) * alea
            + f64::from(nma) * alma
            + f64::from(nju) * alju
            + f64::from(nsa) * alsa
            + f64::from(nur) * alur
            + f64::from(nne) * alne
            + f64::from(npa) * apa)
            % D2PI;
        let (sarg, carg) = (arg.sin(), arg.cos());
        dp += f64::from(sp) * sarg + f64::from(cp) * carg;
        de += f64::from(se) * sarg + f64::from(ce) * carg;
    }
    let dpsipl = dp * U2R;
    let depspl = de * U2R;

    let dpsi = dpsils + dpsipl;
    let deps = depsls + depspl;
    if dpsi.is_finite() && deps.is_finite() {
        Some((dpsi, deps))
    } else {
        None
    }
}

fn nutation_angles_06a(jd_tt: f64) -> Option<(f64, f64)> {
    if !jd_tt.is_finite() {
        return None;
    }
    let t = (jd_tt - 2451545.0) / 36525.0;
    let fj2 = -2.7774e-6 * t;
    let (dp, de) = nutation_angles_2000a(jd_tt)?;
    Some((dp + dp * (0.4697e-6 + fj2), de + de * fj2))
}

pub fn nutation_matrix_n06a(jd_tt: f64) -> Option<Mat3> {
    if !jd_tt.is_finite() {
        return None;
    }
    let t = (jd_tt - 2451545.0) / 36525.0;
    let (dpsi, deps) = nutation_angles_06a(jd_tt)?;
    let epsa = mean_obliquity_06_rad(t);
    let n = mat_mul(&rx(-(epsa + deps)), &mat_mul(&rz(-dpsi), &rx(epsa)));
    if n.iter().all(|row| row.iter().all(|c| c.is_finite())) {
        Some(n)
    } else {
        None
    }
}

pub fn cirs_to_gcrs(r_cirs_km: [f64; 3], tdb_jd: f64) -> Option<[f64; 3]> {
    if !finite3(r_cirs_km) {
        return None;
    }
    let p = precession_matrix_fw06(tdb_jd)?;
    let n = nutation_matrix_n06a(tdb_jd)?;
    let r = mat_mul(&p, &n);
    let out = mat_apply(&mat_transpose(&r), r_cirs_km);
    if finite3(out) { Some(out) } else { None }
}

pub fn itrf_to_icrs(
    r_itrf_km: [f64; 3],
    ut1_jd: f64,
    tdb_jd: f64,
    eop: &EopSample,
) -> Option<[f64; 3]> {
    let r_cirs = itrf_to_cirs(r_itrf_km, ut1_jd, eop)?;
    cirs_to_gcrs(r_cirs, tdb_jd)
}

