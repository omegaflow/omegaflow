fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let mut roots: Vec<String> = Vec::new();
    let mut lines_per_file = 2usize;
    let mut max_files = 40usize;
    let mut max_mb = 100u64;
    let mut max_results = net::DEFAULT_MAX;
    let mut skip = 0usize;
    let mut binary = false;
    let mut content = false;
    let mut kind = index::Kind::Any;
    let mut sort = index::Sort::Name;
    let mut keywords: Vec<String> = Vec::new();
    let mut modes: Vec<Mode> = Vec::new();
    let mut mft_path: Option<String> = None;
    let mut serve_addr: Option<String> = None;
    let mut verdict_url: Option<String> = None;
    let mut jina_input: Option<String> = None;
    let mut playwright_input: Option<String> = None;
    let mut pdf_input: Option<String> = None;
    let mut pdf_out: Option<String> = None;
    let mut arxiv_input: Option<String> = None;
    let mut oai_input: Option<String> = None;
    let mut oai_pages: Option<usize> = None;
    let mut count_only = false;
    let mut case_sensitive = false;
    let mut path_match = false;
    let mut include_glob: Option<String> = None;
    let mut headed = false;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--serve" => {
                modes.push(Mode::Serve);
                if let Some(a) = args.get(i + 1) {
                    if a.contains(':') && !a.starts_with('-') {
                        serve_addr = Some(a.clone());
                        i += 1;
                    }
                }
            }
            "--mft" => {
                i += 1;
                if let Some(p) = args.get(i) {
                    mft_path = Some(p.clone());
                }
                modes.push(Mode::Mft);
            }
            "--verdict" => {
                i += 1;
                if let Some(u) = args.get(i) {
                    verdict_url = Some(u.clone());
                }
                modes.push(Mode::Verdict);
            }
            "--jina" => {
                i += 1;
                if let Some(u) = args.get(i) {
                    jina_input = Some(u.clone());
                }
                modes.push(Mode::Jina);
            }
            "--cacert" => {
                i += 1;
                if let Some(p) = args.get(i) {
                    net::set_ca_bundle(p);
                }
            }
            "--playwright" => {
                i += 1;
                if let Some(u) = args.get(i) {
                    playwright_input = Some(u.clone());
                }
                modes.push(Mode::Playwright);
            }
            "--pdf-image" => {
                i += 1;
                if let Some(p) = args.get(i) {
                    pdf_input = Some(p.clone());
                }
                modes.push(Mode::PdfImage);
            }
            "--pdf-text" => {
                i += 1;
                if let Some(p) = args.get(i) {
                    pdf_input = Some(p.clone());
                }
                modes.push(Mode::PdfText);
            }
            "--arxiv-src" => {
                i += 1;
                if let Some(p) = args.get(i) {
                    arxiv_input = Some(p.clone());
                }
                modes.push(Mode::ArxivSrc);
            }
            "--out" => {
                i += 1;
                if let Some(d) = args.get(i) {
                    pdf_out = Some(d.clone());
                }
            }
            "--headed" => headed = true,
            "--stop" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    net::set_all_stop(n);
                }
            }
            "--arxiv-oai" => {
                modes.push(Mode::Oai);
                if let Some(a) = args.get(i + 1) {
                    if !a.starts_with('-') {
                        oai_input = Some(a.clone());
                        i += 1;
                    }
                }
            }
            "--pages" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    oai_pages = Some(n);
                }
            }
            "--kind" => {
                i += 1;
                if let Some(v) = args.get(i) {
                    kind = match v.as_str() {
                        "file" => index::Kind::File,
                        "dir" => index::Kind::Dir,
                        _ => index::Kind::Any,
                    };
                }
            }
            "--sort" => {
                i += 1;
                if let Some(v) = args.get(i) {
                    sort = match v.as_str() {
                        "size" => index::Sort::Size,
                        "mtime" => index::Sort::Mtime,
                        _ => index::Sort::Name,
                    };
                }
            }
            "--root" => {
                i += 1;
                if let Some(r) = args.get(i) {
                    roots.push(r.clone());
                }
            }
            "--lines" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    lines_per_file = n;
                }
            }
            "--files" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    max_files = n;
                }
            }
            "--max-mb" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    max_mb = n;
                }
            }
            "--max" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    max_results = n;
                }
            }
            "--skip" => {
                i += 1;
                if let Some(n) = args.get(i).and_then(|s| s.parse().ok()) {
                    skip = n;
                }
            }
            "--binary" => binary = true,
            "--content" => content = true,
            "--count" => count_only = true,
            "--case" => case_sensitive = true,
            "--path" => path_match = true,
            "--include" => {
                i += 1;
                if let Some(g) = args.get(i) {
                    include_glob = Some(g.clone());
                }
            }
            "--values" => {
                i += 1;
                match args.get(i) {
                    Some(v) => {
                        keywords.push("values".to_string());
                        keywords.push(v.clone());
                    }
                    None => {
                        eprintln!("archive_search: --values needs a variable name");
                        std::process::exit(2);
                    }
                }
            }
            "--help" | "-h" => {
                usage();
                std::process::exit(0);
            }
            other => {
                if let Some(m) = flag_mode(other) {
                    modes.push(m);
                } else if other.starts_with('-') {
                    eprintln!("archive_search: unknown option {other}");
                    usage();
                    std::process::exit(2);
                } else {
                    keywords.push(other.to_string());
                }
            }
        }
        i += 1;
    }

    if modes.is_empty() {
        modes.push(Mode::Plain);
    }
    let multi = modes.len() > 1;
    for mode in modes {
        if multi {
            out!("=== archive_search --{} ===", mode.label());
        }
        match mode {
            Mode::Plain => {
                if keywords.is_empty() {
                    if std::io::stdin().is_terminal() {
                        usage();
                        std::process::exit(2);
                    }
                    let stdin = std::io::stdin();
                    let mut reader = stdin.lock();
                    let mut line = String::new();
                    loop {
                        line.clear();
                        let n = match reader.read_line(&mut line) {
                            Ok(n) => n,
                            Err(e) => {
                                eprintln!("archive_search: stdin read ends: {e}");
                                break;
                            }
                        };
                        if n == 0 {
                            break;
                        }
                        let query = line.trim();
                        if query.is_empty() {
                            continue;
                        }
                        let kws: Vec<String> =
                            query.split_whitespace().map(|s| s.to_string()).collect();
                        run_plain(
                            &roots,
                            &kws,
                            lines_per_file,
                            max_files,
                            max_mb,
                            skip,
                            binary,
                            case_sensitive,
                            count_only,
                            include_glob.as_deref(),
                        );
                    }
                } else {
                    run_plain(
                        &roots,
                        &keywords,
                        lines_per_file,
                        max_files,
                        max_mb,
                        skip,
                        binary,
                        case_sensitive,
                        count_only,
                        include_glob.as_deref(),
                    );
                }
            }
            Mode::Leads => run_leads(&roots, &keywords, lines_per_file, max_files, max_mb),
            Mode::Mft => {
                let device = match &mft_path {
                    Some(p) => p.clone(),
                    None => {
                        eprintln!("archive_search --mft: the mode carries no device path");
                        std::process::exit(2);
                    }
                };
                let lines =
                    ntfs::run_lines(Path::new(&device), &keywords, max_files, max_mb, content);
                print_lines(&lines);
            }
            Mode::Index => {
                let lines = run_index(&roots, &keywords, max_files, kind, sort, path_match);
                print_lines(&lines);
            }
            Mode::Serve => run_serve(serve_addr.clone(), &roots, mft_path.clone()),
            Mode::Git => {
                let repo = match find_repo_root() {
                    Some(r) => r,
                    None => PathBuf::from("."),
                };
                let query = keywords.join(" ");
                let lines = git::run_lines(&repo, &query);
                print_lines(&lines);
            }
            Mode::Verdict => {
                let url = match &verdict_url {
                    Some(u) => u.clone(),
                    None => {
                        eprintln!("archive_search --verdict: the mode carries no url");
                        std::process::exit(2);
                    }
                };
                let lines = net::verdict_lines(&url);
                print_lines(&lines);
            }
            Mode::Jina => {
                let url = match &jina_input {
                    Some(u) => u.clone(),
                    None => {
                        eprintln!("archive_search --jina: the mode carries no url");
                        std::process::exit(2);
                    }
                };
                let lines = jina::jina_lines(&url);
                print_lines(&lines);
            }
            Mode::Playwright => {
                let input = match &playwright_input {
                    Some(u) => u.clone(),
                    None => {
                        eprintln!("archive_search --playwright: the mode carries no url");
                        std::process::exit(2);
                    }
                };
                let lines = playwright::run_lines(&input, headed);
                print_lines(&lines);
            }
            Mode::PdfImage => {
                let input = match &pdf_input {
                    Some(p) => p.clone(),
                    None => {
                        eprintln!("archive_search --pdf-image: the mode carries no file or url");
                        std::process::exit(2);
                    }
                };
                let lines = run_pdf_image(&input, pdf_out.as_deref());
                print_lines(&lines);
            }
            Mode::PdfText => {
                let input = match &pdf_input {
                    Some(p) => p.clone(),
                    None => {
                        eprintln!("archive_search --pdf-text: the mode carries no file or url");
                        std::process::exit(2);
                    }
                };
                let lines = run_pdf_text(&input);
                print_lines(&lines);
            }
            Mode::ArxivSrc => {
                let input = match &arxiv_input {
                    Some(p) => p.clone(),
                    None => {
                        eprintln!("archive_search --arxiv-src: the mode carries no id or url");
                        std::process::exit(2);
                    }
                };
                let lines = arxiv_src::run_lines(&input, pdf_out.as_deref());
                print_lines(&lines);
            }
            Mode::Oai => {
                let lines = oai::arxiv_oai_lines(oai_input.as_deref(), oai_pages);
                print_lines(&lines);
            }
            Mode::Consensus => {
                let query = keywords.join(" ");
                let env_map = match find_repo_root() {
                    Some(repo) => secrets::load_env(&repo),
                    None => env::vars().collect(),
                };
                let key = secrets::resolve_key(
                    env_map
                        .get("CONSENSUS_API_KEY")
                        .map(String::as_str)
                        .unwrap_or(""),
                    &env_map,
                );
                let lines = match key {
                    secrets::Secret::Value(t) => consensus::consensus_lines(&query, &t, 10),
                    secrets::Secret::Absent(marker) => {
                        let name = match marker {
                            Some(m) => format!("CONSENSUS_API_KEY marker {{{m}}}"),
                            None => "CONSENSUS_API_KEY".to_string(),
                        };
                        vec![format!(
                            "pending — {} absent from .secrets.local/.env",
                            name
                        )]
                    }
                };
                print_lines(&lines);
            }
            Mode::Lasair => {
                let query = keywords.join(" ");
                let lines = lasair::lasair_lines(&query);
                print_lines(&lines);
            }
            Mode::Perplexity => {
                let query = keywords.join(" ");
                let lines = perplexity::perplexity_lines(&query);
                print_lines(&lines);
            }
            Mode::Lpf => {
                let query = keywords.join(" ");
                let lines = lpf::lpf_lines(&query);
                print_lines(&lines);
            }
            Mode::Gosat => {
                let query = keywords.join(" ");
                let lines = gosat::gosat_lines(&query);
                print_lines(&lines);
            }
            Mode::Stats => {
                print_lines(&run_stats());
            }
            Mode::Net(name) => {
                let env_map = match find_repo_root() {
                    Some(repo) => secrets::load_env(&repo),
                    None => env::vars().collect(),
                };
                if keywords.is_empty()
                    && !net::is_auth_mode(name)
                    && !std::io::stdin().is_terminal()
                {
                    let stdin = std::io::stdin();
                    let mut reader = stdin.lock();
                    let mut line = String::new();
                    loop {
                        line.clear();
                        let n = match reader.read_line(&mut line) {
                            Ok(n) => n,
                            Err(_) => break,
                        };
                        if n == 0 {
                            break;
                        }
                        let query = line.trim();
                        if query.is_empty() {
                            continue;
                        }
                        let lines = net::run_lines_max(
                            name,
                            query,
                            &env_map,
                            pdf_out.as_deref(),
                            max_results,
                        );
                        print_lines(&lines);
                    }
                } else {
                    let query = keywords.join(" ");
                    let lines =
                        net::run_lines_max(name, &query, &env_map, pdf_out.as_deref(), max_results);
                    print_lines(&lines);
                }
            }
        }
    }
}

fn run_stats() -> Vec<String> {
    let Some(log) = net::log_dir() else {
        return vec!["--stats — no scratch root; the query log stays unread".to_string()];
    };
    let path = log.join("queries.φ");
    let body = match std::fs::read_to_string(&path) {
        Ok(b) => b,
        Err(_) => {
            return vec![format!(
                "--stats — {} absent; no query measured yet (the log grows with each network run)",
                path.display()
            )];
        }
    };
    let mut runs: std::collections::HashMap<String, (u64, u64, u64, u64)> =
        std::collections::HashMap::new();
    let mut total = 0u64;
    for line in body.lines() {
        let f: Vec<&str> = line.splitn(6, " | ").collect();
        if f.len() < 5 {
            continue;
        }
        let mode = f[2].trim().to_string();
        let n: u64 = match f[3].trim().parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        let h: u64 = match f[4].trim().parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        let e = runs.entry(mode).or_insert((0, 0, 0, 0));
        e.0 += 1;
        e.1 += h;
        e.2 += n;
        if h == 0 {
            e.3 += 1;
        }
        total += 1;
    }
    if total == 0 {
        return vec!["--stats — the query log carries no line yet".to_string()];
    }
    let mut rows: Vec<(String, u64, u64, u64, u64)> = runs
        .into_iter()
        .map(|(m, (r, h, n, e))| (m, r, h, n, e))
        .collect();
    rows.sort_by(|a, b| {
        let ya = a.2 as f64 / a.1 as f64;
        let yb = b.2 as f64 / b.1 as f64;
        yb.partial_cmp(&ya).unwrap_or(std::cmp::Ordering::Equal)
    });
    let mut out = vec![format!(
        "=== archive_search --stats — arm yield over {total} logged queries ({}) ===",
        path.display()
    )];
    out.push("mode\truns\thits\thits/run\tempty\tsum_lines".to_string());
    for (m, r, h, n, e) in rows {
        out.push(format!(
            "{m}\t{r}\t{h}\t{:.1}\t{e}\t{n}",
            h as f64 / r as f64
        ));
    }
    out
}

