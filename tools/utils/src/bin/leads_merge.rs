use std::collections::{BTreeMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

const REGISTERS: [&str; 5] = [
    "phi/sources.φ",
    "phi/declined_sources.φ",
    "phi/dead_sources.φ",
    "phi/blocked_sources.φ",
    "phi/witnesses.φ",
];

fn collect_files(dir: &str) -> Vec<PathBuf> {
    let mut out = Vec::new();
    if let Ok(read) = fs::read_dir(dir) {
        for entry in read.flatten() {
            let path = entry.path();
            if path.extension().and_then(|s| s.to_str()) == Some("φ") {
                out.push(path);
            }
        }
    }
    out.sort();
    out
}

fn host_of(token: &str) -> String {
    let s = token.trim();
    let s = match s.strip_prefix("https://") {
        Some(rest) => rest,
        None => match s.strip_prefix("http://") {
            Some(rest) => rest,
            None => s,
        },
    };
    let s = s.split('/').next().unwrap_or(s);
    let s = s.split('?').next().unwrap_or(s);
    s.trim_start_matches("www.").to_lowercase()
}

fn register_hosts() -> HashSet<String> {
    let mut hosts = HashSet::new();
    for reg in REGISTERS {
        let Ok(text) = fs::read_to_string(reg) else {
            continue;
        };
        for raw in text.lines() {
            let line = raw.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let key = line.split_whitespace().next().unwrap_or("");
            if key == "url" || key == "tag" || key == "origin" {
                for token in line.split_whitespace() {
                    if token.contains("://") || token.contains('.') && !token.starts_with('-') {
                        let h = host_of(token);
                        if h.contains('.') {
                            hosts.insert(h);
                        }
                    }
                }
            }
        }
    }
    hosts
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let mut out_path = "phi/pipeline/leads.φ".to_string();
    let mut inputs: Vec<PathBuf> = Vec::new();
    let mut dedup_registers = true;
    let mut i = 1;
    while i < args.len() {
        match args[i].as_str() {
            "--out" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("leads_merge --out <file> [--keep-registered] [<input>...]");
                    std::process::exit(2);
                }
                out_path = args[i].clone();
            }
            "--keep-registered" => dedup_registers = false,
            other => inputs.push(PathBuf::from(other)),
        }
        i += 1;
    }
    if inputs.is_empty() {
        inputs.extend(collect_files("phi/pipeline/queue"));
        inputs.extend(collect_files("phi/pipeline/stage"));
    }
    if inputs.is_empty() {
        eprintln!("leads_merge: no input files");
        std::process::exit(2);
    }

    let curated = if dedup_registers {
        register_hosts()
    } else {
        HashSet::new()
    };

    let mut map: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut url_lines = 0usize;
    let mut dropped_registered = 0usize;
    let mut dup_directives = 0usize;
    for file in &inputs {
        let Ok(text) = fs::read_to_string(file) else {
            eprintln!("leads_merge: unreadable {}", file.display());
            continue;
        };
        let mut cur: Option<String> = None;
        for raw in text.lines() {
            let line = raw.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Some(u) = line.strip_prefix("url ") {
                let u = u.trim().to_string();
                if u.is_empty() {
                    continue;
                }
                url_lines += 1;
                if curated.contains(&host_of(&u)) {
                    dropped_registered += 1;
                    cur = None;
                    continue;
                }
                map.entry(u.clone()).or_default();
                cur = Some(u);
            } else if let Some(u) = &cur {
                let entry = map.get_mut(u).expect("url was inserted");
                if entry.iter().any(|d| d == line) {
                    dup_directives += 1;
                } else {
                    entry.push(line.to_string());
                }
            }
        }
    }

    let mut out = String::from(
        "# leads — the one candidate file (un-registered sources only; generated by leads_merge)\n",
    );
    for (url, directives) in &map {
        out.push_str(&format!("url {}\n", url));
        for d in directives {
            out.push_str(&format!("  {}\n", d));
        }
    }
    if let Some(parent) = Path::new(&out_path).parent() {
        let _ = fs::create_dir_all(parent);
    }
    if let Err(e) = fs::write(&out_path, out) {
        eprintln!("leads_merge: write {} failed: {}", out_path, e);
        std::process::exit(2);
    }
    println!(
        "leads_merge: {} input files -> {} | {} url lines -> {} unique urls kept, {} dropped (already registered), {} directive-dups collapsed",
        inputs.len(),
        out_path,
        url_lines,
        map.len(),
        dropped_registered,
        dup_directives
    );
}
